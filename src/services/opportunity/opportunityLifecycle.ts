/**
 * Export the signal store for a workspace.
 */
export function exportSignalStore(workspaceId: string): OpportunitySignalStore {
  return getSignalStore(workspaceId);
}

/**
 * Import a signal store into a workspace.
 */
export function importSignalStore(workspaceId: string, store: OpportunitySignalStore): void {
  signalStores.set(workspaceId, {
    signals: store.signals,
    dismissedIds: store.dismissedIds,
    savedIds: store.savedIds,
    updatedAt: new Date().toISOString(),
  });
}

/**
 * Clear the store for a workspace (testing only).
 */
export function clearSignalStore(workspaceId: string): void {
  signalStores.delete(workspaceId);
}
