/**
 * Transition a signal to QUALIFIED.
 */
export function qualifySignal(workspaceId: string, signalId: string): OpportunitySignal | undefined {
  return transitionSignal(workspaceId, signalId, 'QUALIFIED');
}

/**
 * Dismiss a signal (prevents rediscovery).
 */
export function dismissSignal(params: {
  workspaceId: string;
  signalId: string;
  reason?: string;
}): OpportunitySignal | undefined {
  const store = getSignalStore(params.workspaceId);
  const signal = store.signals.find((s) => s.id === params.signalId);
  if (!signal) return undefined;

  signal.lifecycleState = 'DISMISSED';
  signal.transitions.DISMISSED = new Date().toISOString();
  signal.dismissedReason = params.reason;
  signal.updatedAt = new Date().toISOString();

  store.dismissedIds.add(signal.id);
  store.updatedAt = new Date().toISOString();
  signalStores.set(params.workspaceId, store);

  return signal;
}

