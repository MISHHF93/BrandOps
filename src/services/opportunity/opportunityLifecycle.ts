/**
 * Generic signal transition.
 */
function transitionSignal(
  workspaceId: string,
  signalId: string,
  newState: OpportunityLifecycleState
): OpportunitySignal | undefined {
  const store = getSignalStore(workspaceId);
  const signal = store.signals.find((s) => s.id === signalId);
  if (!signal) return undefined;

  signal.lifecycleState = newState;
  signal.transitions[newState] = new Date().toISOString();
  signal.updatedAt = new Date().toISOString();

  store.updatedAt = new Date().toISOString();
  signalStores.set(workspaceId, store);

  return signal;
}

// ---------------------------------------------------------------------------
// Rediscovery Prevention
// ---------------------------------------------------------------------------

/**
 * Check if a signal has been dismissed (prevents rediscovery).
 */
export function isDismissed(workspaceId: string, signalId: string): boolean {
  const store = getSignalStore(workspaceId);
  return store.dismissedIds.has(signalId);
}

/**
 * Filter out dismissed signals from a list of recommendations.
 * This is the key function for Opportunity Radar integration.
 */
export function filterDismissedSignals<T extends { id: string }>(
  workspaceId: string,
  recommendations: T[]
): T[] {
  const store = getSignalStore(workspaceId);
  return recommendations.filter((r) => !store.dismissedIds.has(r.id));
}

/**
 * Check if a signal id matches a dismissed signal (by id or by source recommendation id).
 */
export function isSignalDismissedBySourceId(workspaceId: string, sourceRecommendationId: string): boolean {
  const store = getSignalStore(workspaceId);
  return store.signals.some(
    (s) => s.sourceRecommendationId === sourceRecommendationId && s.lifecycleState === 'DISMISSED'
  );
}

